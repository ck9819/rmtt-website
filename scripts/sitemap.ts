// Regenerates public/sitemap.xml from siteConfig.siteUrl and published news. Run: bun scripts/sitemap.ts
import { readFileSync, writeFileSync } from 'node:fs';
import { siteConfig } from '../src/lib/siteConfig';
import { publishedNews } from '../src/data/news';
const file = new URL('../public/sitemap.xml', import.meta.url);
const old = readFileSync(file, 'utf8');
const paths = [...old.matchAll(/<loc>[^<]*#(\/[^<]*)<\/loc>/g)].map(m => m[1]).filter(p => !p.startsWith('/news/'));
const all = [...new Set([...paths, '/news', ...publishedNews.map(n => `/news/${n.id}`)])];
writeFileSync(file, `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/sitemap.ts. HashRouter fragments are not separately indexable by search engines.
     lastmod is omitted because authoritative page-specific content dates are unavailable. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${all.map(p => `  <url><loc>${siteConfig.siteUrl}/#${p}</loc></url>`).join('\n')}
</urlset>
`);
